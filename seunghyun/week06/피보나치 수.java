/**
 * @풀이
 *
 * DP
 *
 * 
 * @처리순서
 *
 * 1. 피보나치 수를 저장할 DP 배열 생성
 *
 * 2. DP[0] = 0, DP[1] = 1로 초기화
 *
 * 3. 2부터 n까지 반복
 *
 * 4. 현재 피보나치 수를
 *    이전 두 피보나치 수의 합으로 계산
 *
 * 5. 계산할 때마다 1234567로 나눈 나머지를 저장
 *    -> 숫자가 너무 커지는 것을 방지
 *
 * 6. DP[n] 반환
 *
 *
 * @시간복잡도
 *
 * O(N)
 *
 *
 * @공간복잡도
 *
 * O(N)
 *
 */

class Solution {

    public int solution(int n) {
        // 피보나치 수를 저장할 배열
        int[] dp = new int[n + 1];

        // 초기값
        dp[0] = 0;
        dp[1] = 1;

        // 2부터 n까지 피보나치 수 계산
        for (int i = 2; i <= n; i++) {
            // 이전 두 값을 더한 뒤
            // 1234567로 나눈 나머지를 저장
            dp[i] = (dp[i - 1] + dp[i - 2]) % 1234567;
        }

        return dp[n];
    }
}
